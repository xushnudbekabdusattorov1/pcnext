// Deterministic hash to assign stable mock stock counts for all components
function getMockInventory(id: string): { stockStatus: StockStatus; stockCount: number } {
  if (LIMITED_AVAILABILITY_IDS[id]) {
    return LIMITED_AVAILABILITY_IDS[id];
  }

  // Stable numeric hash from string id
  let hash = 0;
  for (let i = 0; i < id.length; i++) {
    hash = (hash << 5) - hash + id.charCodeAt(i);
    hash |= 0;
  }
  const positiveHash = Math.abs(hash);

  // Approximately 20% of other components have limited availability
  if (positiveHash % 6 === 0) {
    return {
      stockStatus: 'limited',
      stockCount: (positiveHash % 4) + 2, // 2 to 5 units
    };
  }

  // Remainder are in stock with ample units
  return {
    stockStatus: 'in_stock',
    stockCount: (positiveHash % 25) + 12, // 12 to 36 units
  };
}

